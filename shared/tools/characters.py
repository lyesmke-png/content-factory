#!/usr/bin/env python3
"""Draw the kids-niche characters as layered PNGs for animate-shot.py.

The characters are drawn in code, not generated by an image model. Three
reasons, all practical:

  * character consistency is the hard problem in AI-generated series work; a
    drawing function returns the same face every single time, for ever.
  * it needs no API key, no credits and no licence: the art is ours.
  * limited animation wants flat shapes with a separable mouth and eyes, which
    is exactly what this produces and exactly what an image model does not.

Style follows what the reference study measured: flat colour, thick outline,
oversized head, close-up framing, no fine detail (the frame is watched at
phone size, often 360px wide).

Usage:
    python shared/tools/characters.py <out-dir> --who samsam --shot closeup
"""
import argparse
import json
import pathlib

from PIL import Image, ImageDraw

W, H = 1080, 1920
OUTLINE = (58, 44, 40, 255)
LW = 10

PALETTE = {
    "samsam": {"fur": (176, 180, 190), "inner": (236, 186, 190),
               "shirt": (92, 150, 196)},
    "noor": {"skin": (238, 198, 164), "skin_dark": (214, 170, 138),
             "hair": (62, 48, 46), "shirt": (214, 104, 112)},
}


def layer():
    return Image.new("RGBA", (W, H), (0, 0, 0, 0))


def ellipse(d, box, fill, outline=True):
    d.ellipse(box, fill=fill, outline=OUTLINE if outline else None,
              width=LW if outline else 0)


def draw_room(sun="day"):
    """One reusable interior; the references used three backgrounds in total."""
    img = layer()
    d = ImageDraw.Draw(img)
    wall = (247, 231, 206) if sun == "day" else (190, 196, 226)
    floor = (206, 170, 134) if sun == "day" else (158, 142, 150)
    d.rectangle([0, 0, W, int(H * 0.72)], fill=wall)
    d.rectangle([0, int(H * 0.72), W, H], fill=floor)
    d.line([(0, int(H * 0.72)), (W, int(H * 0.72))], fill=OUTLINE, width=LW)
    d.rounded_rectangle([120, 300, 480, 760], 40, fill=(168, 212, 236),
                        outline=OUTLINE, width=LW)
    d.line([(300, 300), (300, 760)], fill=OUTLINE, width=LW)
    d.line([(120, 530), (480, 530)], fill=OUTLINE, width=LW)
    d.rectangle([640, 620, 1010, 650], fill=(166, 128, 96),
                outline=OUTLINE, width=LW)
    d.rounded_rectangle([760, 500, 880, 620], 18, fill=(78, 138, 200),
                        outline=OUTLINE, width=LW)
    d.arc([860, 520, 930, 600], 270, 90, fill=OUTLINE, width=LW)
    return img


def samsam_body(scale=1.0, dy=0):
    """Grey rabbit with no mouth and no eyes: those are separate layers."""
    c = PALETTE["samsam"]
    img = layer()
    d = ImageDraw.Draw(img)
    cx, cy = W // 2, int(H * 0.52) + dy
    hw, hh = int(330 * scale), int(300 * scale)
    for sx in (-1, 1):
        ex = cx + sx * int(150 * scale)
        ellipse(d, [ex - int(66 * scale), cy - hh - int(330 * scale),
                    ex + int(66 * scale), cy - hh + int(60 * scale)], c["fur"])
        ellipse(d, [ex - int(30 * scale), cy - hh - int(280 * scale),
                    ex + int(30 * scale), cy - hh + int(20 * scale)],
                c["inner"], outline=False)
    ellipse(d, [cx - int(300 * scale), cy + int(170 * scale),
                cx + int(300 * scale), cy + int(760 * scale)], c["shirt"])
    ellipse(d, [cx - hw, cy - hh, cx + hw, cy + hh], c["fur"])
    for sx in (-1, 1):
        ellipse(d, [cx + sx * int(210 * scale) - int(58 * scale),
                    cy + int(60 * scale),
                    cx + sx * int(210 * scale) + int(58 * scale),
                    cy + int(150 * scale)], (236, 176, 180), outline=False)
    ellipse(d, [cx - int(34 * scale), cy + int(10 * scale),
                cx + int(34 * scale), cy + int(62 * scale)], c["inner"])
    return img, (cx, cy, scale)


def noor_body(scale=1.0, dy=0):
    c = PALETTE["noor"]
    img = layer()
    d = ImageDraw.Draw(img)
    cx, cy = W // 2, int(H * 0.52) + dy
    hw, hh = int(300 * scale), int(320 * scale)
    ellipse(d, [cx - hw - int(60 * scale), cy - hh - int(70 * scale),
                cx + hw + int(60 * scale), cy + hh + int(140 * scale)], c["hair"])
    ellipse(d, [cx - int(300 * scale), cy + int(200 * scale),
                cx + int(300 * scale), cy + int(780 * scale)], c["shirt"])
    ellipse(d, [cx - hw, cy - hh + int(40 * scale), cx + hw, cy + hh], c["skin"])
    d.pieslice([cx - hw - int(10 * scale), cy - hh - int(10 * scale),
                cx + hw + int(10 * scale), cy + int(170 * scale)],
               185, 355, fill=c["hair"], outline=OUTLINE, width=LW)
    for sx in (-1, 1):
        ellipse(d, [cx + sx * int(205 * scale) - int(54 * scale),
                    cy + int(90 * scale),
                    cx + sx * int(205 * scale) + int(54 * scale),
                    cy + int(166 * scale)], (232, 160, 160), outline=False)
    ellipse(d, [cx - int(26 * scale), cy + int(40 * scale),
                cx + int(26 * scale), cy + int(92 * scale)],
            c["skin_dark"], outline=False)
    return img, (cx, cy, scale)


def eyes(scale, shut=False, mood="neutral"):
    """Returned as a small tile; shot.json carries where it is pasted."""
    w, h = int(430 * scale), int(230 * scale)
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    r = int(74 * scale)
    for ex in (int(110 * scale), w - int(110 * scale)):
        if shut:
            d.arc([ex - r, h // 2 - r, ex + r, h // 2 + r], 200, 340,
                  fill=OUTLINE, width=int(13 * scale))
        else:
            ellipse(d, [ex - r, h // 2 - r, ex + r, h // 2 + r], (255, 255, 255))
            d.ellipse([ex - int(32 * scale), h // 2 - int(18 * scale),
                       ex + int(32 * scale), h // 2 + int(46 * scale)],
                      fill=(36, 32, 40))
            d.ellipse([ex - int(10 * scale), h // 2 - int(10 * scale),
                       ex + int(14 * scale), h // 2 + int(14 * scale)],
                      fill=(255, 255, 255))
        if mood == "sad":
            d.arc([ex - r - 6, h // 2 - r - int(60 * scale),
                   ex + r + 6, h // 2 - int(10 * scale)], 210, 330,
                  fill=OUTLINE, width=int(14 * scale))
    return img


def mouth(scale, level, kind="samsam"):
    """Four shapes: shut, narrow, open, wide. Level 0 is silence."""
    size = int(300 * scale)
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    c = size // 2
    specs = [(int(130 * scale), int(22 * scale)),
             (int(118 * scale), int(62 * scale)),
             (int(104 * scale), int(112 * scale)),
             (int(96 * scale), int(156 * scale))]
    w, h = specs[level]
    if level == 0:
        d.line([(c - w // 2, c), (c + w // 2, c)], fill=OUTLINE,
               width=int(14 * scale))
        return img
    ellipse(d, [c - w // 2, c - h // 2, c + w // 2, c + h // 2], (96, 48, 54))
    if level >= 2:
        d.ellipse([c - w // 3, c + h // 8, c + w // 3,
                   c + h // 2 - int(8 * scale)], fill=(222, 118, 128))
    if kind == "samsam" and level >= 1:
        d.rounded_rectangle([c - int(30 * scale), c - h // 2 + int(2 * scale),
                             c + int(30 * scale), c - h // 2 + int(42 * scale)],
                            8, fill=(255, 255, 255))
    return img


SHOTS = {"closeup": (1.00, 120), "wide": (0.58, -140)}


def build(out_dir, who, shot, mood, sun):
    out = pathlib.Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    scale, dy = SHOTS[shot]
    draw_room(sun).save(out / "bg.png")
    body, (cx, cy, s) = (samsam_body if who == "samsam" else noor_body)(scale, dy)
    body.save(out / "body.png")

    e_open = eyes(s, False, mood)
    eyes(s, True, mood).save(out / "eyes-shut.png")
    e_open.save(out / "eyes-open.png")
    eye_pos = (cx - e_open.width // 2, cy - int(150 * s) - e_open.height // 2)

    m0 = mouth(s, 0, who)
    for i in range(4):
        mouth(s, i, who).save(out / ("mouth-%d.png" % i))
    mouth_pos = (cx - m0.width // 2, cy + int(130 * s) - m0.height // 2)

    (out / "shot.json").write_text(json.dumps({
        "size": [W, H],
        "mouth": {"pos": list(mouth_pos), "level_db": [-44, -32, -22]},
        "eyes": {"pos": list(eye_pos), "blink_every": [2.4, 4.8]},
        "camera": {"zoom": 1.08 if shot == "closeup" else 1.14,
                   "pan": "up" if shot == "closeup" else "down"},
    }, indent=2), encoding="utf-8")
    print("%s  %s/%s" % (out, who, shot))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out_dir")
    ap.add_argument("--who", choices=["samsam", "noor"], required=True)
    ap.add_argument("--shot", choices=list(SHOTS), default="closeup")
    ap.add_argument("--mood", choices=["neutral", "sad"], default="neutral")
    ap.add_argument("--sun", choices=["day", "evening"], default="day")
    a = ap.parse_args()
    build(a.out_dir, a.who, a.shot, a.mood, a.sun)


if __name__ == "__main__":
    main()
